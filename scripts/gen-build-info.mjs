import { execSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))

function formatCommittedAtLabel(iso) {
  if (!iso) return null
  return new Date(iso).toLocaleString('fr-FR', {
    timeZone: 'Europe/Paris',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}

function readGitCommitAt(sha) {
  const ref = sha || 'HEAD'
  return execSync(`git show -s --format=%cI ${ref}`, { encoding: 'utf8' }).trim()
}

export function getBuildInfo() {
  const vercelSha = process.env.VERCEL_GIT_COMMIT_SHA?.trim()

  try {
    const version = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim()
    const fullCommitId = execSync('git rev-parse HEAD', { encoding: 'utf8' }).trim()
    const committedAt = readGitCommitAt()
    return {
      version,
      commitId: version,
      fullCommitId,
      committedAt,
      committedAtLabel: formatCommittedAtLabel(committedAt),
    }
  } catch {
    if (vercelSha) {
      const version = vercelSha.slice(0, 7)
      let committedAt = null
      try {
        committedAt = readGitCommitAt(vercelSha)
      } catch {
        committedAt = new Date().toISOString()
      }
      return {
        version,
        commitId: version,
        fullCommitId: vercelSha,
        committedAt,
        committedAtLabel: formatCommittedAtLabel(committedAt),
      }
    }

    const committedAt = new Date().toISOString()
    return {
      version: 'local',
      commitId: 'local',
      fullCommitId: null,
      committedAt,
      committedAtLabel: formatCommittedAtLabel(committedAt) ?? 'build locale',
    }
  }
}

export function writeBuildInfo(targetRoot = root) {
  const info = getBuildInfo()
  const json = `${JSON.stringify(info, null, 2)}\n`
  writeFileSync(join(targetRoot, 'build-info.json'), json)

  const jsPath = join(targetRoot, 'pipeline', 'src', 'lib', 'buildInfo.generated.js')
  mkdirSync(dirname(jsPath), { recursive: true })
  writeFileSync(
    jsPath,
    `// Auto-generated by scripts/gen-build-info.mjs — do not edit\nexport const BUILD_INFO = ${JSON.stringify(info)}\n`,
  )

  return info
}

if (import.meta.url.endsWith('gen-build-info.mjs')) {
  const info = writeBuildInfo()
  console.log(`✓ build-info ${info.version} · ${info.committedAtLabel}`)
}
